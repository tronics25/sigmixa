import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

// ASAM MDF 3.30 with the values of sigmixa-basic-decoded.csv as measured signals (MDF 3 has no standard for CAN frames), and
// the ASC date as the start: speed and temperature as doubles, and a speed band with value texts.
const output = path.resolve('sample/basic/sigmixa-basic-decoded.mdf');
const csv = readFileSync(path.resolve('sample/basic/sigmixa-basic-decoded.csv'), 'utf8').trim().split(/\r?\n/).slice(1).map((line) => line.split(',').map(Number));
const date = readFileSync(path.resolve('sample/basic/sigmixa-basic.asc'), 'utf8').split(/\r?\n/).find((line) => line.startsWith('date '));
const [, , monthName, day, clock, year] = date.split(/\s+/);
const month = ['jan', 'feb', 'mar', 'apr', 'may', 'jun', 'jul', 'aug', 'sep', 'oct', 'nov', 'dec'].indexOf(monthName.toLowerCase()) + 1;
const [hours, minutes, seconds] = clock.split(':').map(Number);

// Blocks are laid out in the order added; a link names a block by its number (index + 1) and is the byte offset in the block.
const blocks = [];
const add = (id, size, fill = () => undefined) => { const body = Buffer.alloc(size); fill(body); blocks.push({ id, body, links: [] }); return blocks.length; };
const link = (block, at, to) => blocks[block - 1].links.push({ at, to });
const text = (value) => { const body = Buffer.from(`${value}\0`, 'latin1'); blocks.push({ id: 'TX', body, links: [] }); return blocks.length; };
const pad = (value) => String(value).padStart(2, '0');

const header = add('HD', 204, (body) => {
  body.write(`${pad(day)}:${pad(month)}:${year}`, 14, 'latin1'); body.write(`${pad(hours)}:${pad(minutes)}:${pad(Math.floor(seconds))}`, 24, 'latin1');
  // No nanosecond time stamp: it would need a UTC offset, which the ASC date does not give. The date and time text is the start.
  body.write('SigMixa', 32, 'latin1');
});
const channel = (name, type, bit, bits, dataType) => add('CN', 224, (body) => { body.writeUInt16LE(type, 20); body.write(name, 22, 'latin1'); body.writeUInt16LE(bit, 182); body.writeUInt16LE(bits, 184); body.writeUInt16LE(dataType, 186); });
const conversion = (type, unit, values) => add('CC', 42 + 8 * values.length, (body) => { body.write(unit, 18, 'latin1'); body.writeUInt16LE(type, 38); body.writeUInt16LE(type === 0 ? 2 : values.length / 2, 40); values.forEach((value, i) => body.writeDoubleLE(value, 42 + 8 * i)); });
// Value texts (CC 11): [value, 32-character text] entries.
const texts = (entries) => add('CC', 42 + 40 * entries.length, (body) => { body.writeUInt16LE(11, 38); body.writeUInt16LE(entries.length, 40); entries.forEach(([value, label], i) => { body.writeDoubleLE(value, 42 + 40 * i); body.write(label, 42 + 40 * i + 8, 'latin1'); }); });

const time = channel('Time', 1, 0, 64, 3); link(time, 8, conversion(0, 's', [0, 1]));
const speed = channel('Vehicle Speed', 0, 64, 64, 3); link(speed, 8, conversion(0, 'm/s', [0, 1]));
const temperature = channel('Coolant Temperature', 0, 128, 64, 3); link(temperature, 8, conversion(0, '°C', [0, 1]));
const band = channel('Speed Band', 0, 192, 8, 0); link(band, 8, texts([[0, 'Slow'], [1, 'Medium'], [2, 'Fast']]));
link(time, 4, speed); link(speed, 4, temperature); link(temperature, 4, band);
const group = add('CG', 26, (body) => { body.writeUInt16LE(4, 14); body.writeUInt16LE(25, 16); body.writeUInt32LE(csv.length, 18); });
link(group, 8, time); link(group, 12, text('Reference'));
const records = Buffer.alloc(25 * csv.length);
csv.forEach(([milliseconds, speedValue, temperatureValue], i) => {
  records.writeDoubleLE(milliseconds / 1000, 25 * i); records.writeDoubleLE(speedValue, 25 * i + 8);
  records.writeDoubleLE(temperatureValue, 25 * i + 16); records[25 * i + 24] = speedValue < 10 ? 0 : speedValue < 20 ? 1 : 2;
});
blocks.push({ id: '..', body: records, links: [] }); const data = blocks.length;
const dg = add('DG', 24, (body) => body.writeUInt16LE(1, 16)); link(dg, 8, group); link(dg, 16, data);
link(header, 4, dg); link(header, 8, text('Generated by scripts/generate-basic-mdf.mjs from sample/basic/sigmixa-basic-decoded.csv'));

const addresses = []; let address = 64;
for (const block of blocks) { addresses.push(address); address += (block.id === '..' ? 0 : 4) + block.body.length; }
const id = Buffer.alloc(64); id.write('MDF     ', 0, 'ascii'); id.write('3.30    ', 8, 'ascii'); id.write('SigMixa ', 16, 'ascii'); id.writeUInt16LE(330, 28);
const parts = [id];
for (const block of blocks) {
  const body = Buffer.from(block.body);
  for (const { at, to } of block.links) body.writeUInt32LE(addresses[to - 1], at - (block.id === '..' ? 0 : 4));
  if (block.id !== '..') { const head = Buffer.alloc(4); head.write(block.id, 0, 'ascii'); head.writeUInt16LE(4 + body.length, 2); parts.push(head); }
  parts.push(body);
}
writeFileSync(output, Buffer.concat(parts));
console.log(`Generated ${output}: ${csv.length} records of the reference signals`);
